export function pickWeatherDialogueText(
  condition: WeatherCondition,
  seasonId: SeasonId,
  personality: PersonalityId,
  timePeriod: TimePeriodId
): string {
  const weatherPool = WEATHER_PERSONALITY_LINES[condition]?.[personality] ?? [];
  const seasonPool = SEASON_PERSONALITY_LINES[seasonId]?.[personality] ?? [];
  const timeSuffix =
    timePeriod === 'dawn' || timePeriod === 'morning'
      ? '早安呀，'
      : timePeriod === 'night' || timePeriod === 'late_night'
      ? '今晚也辛苦了，'
      : '';

  const combined =
    Math.random() < 0.72 || seasonPool.length === 0 ? weatherPool : seasonPool;
  const chosen =
    combined[Math.floor(Math.random() * combined.length)] ??
    weatherPool[0] ??
    '今天天氣也很適合一起在小屋裡度過溫暖時光呢！';

  if (timeSuffix && Math.random() < 0.3 && !chosen.startsWith('早') && !chosen.startsWith('今')) {
    return `${timeSuffix}${chosen}`;
  }
  return chosen;
}
