export function createInitialFarmPlots(plotCount = 4): CropPlot[] {
  const safeCount = Math.min(8, Math.max(4, plotCount));
  return Array.from({ length: safeCount }, (_, id) => ({
    id,
    cropId: null,
    plantedAt: null,
    durationMs: 0,
  }));
}

